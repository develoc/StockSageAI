#!/bin/bash

# ANSI color codes for terminal output
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
RED='\033[0;31m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

echo -e "${BLUE}=====================================${NC}"
echo -e "${BLUE}   StockSageAI WSL Auth Server       ${NC}"
echo -e "${BLUE}=====================================${NC}"

# Get the IP address of the WSL instance
WSL_IP=$(hostname -I | awk '{print $1}')

echo -e "${YELLOW}Detected WSL IP address: ${CYAN}${WSL_IP}${NC}"
echo -e "${YELLOW}This will be used to allow connections from Windows host.${NC}"

# Check if the auth-server.env file exists
if [ ! -f "auth-server.env" ]; then
  echo -e "${YELLOW}Warning: auth-server.env file not found. Creating default .env file...${NC}"
  echo "# Database Configuration
DATABASE_URL=postgresql://dbadmin:dbadmin@localhost:5432/quantumtrade

# Authentication
JWT_SECRET=your-super-secret-jwt-key-change-this-in-production

# Server Configuration
NODE_ENV=development
PORT=3456

# CORS Configuration - Include Windows host access
CORS_ORIGINS=http://localhost:5000,http://localhost:5173,http://127.0.0.1:5173,http://127.0.0.1:5000,*" > auth-server.env
  echo -e "${GREEN}Created default auth-server.env file.${NC}"
fi

# Create a temporary .env file with the WSL IP for binding
echo "# Generated by wsl-start-auth-server.sh
DATABASE_URL=postgresql://dbadmin:dbadmin@localhost:5432/quantumtrade
JWT_SECRET=your-super-secret-jwt-key-change-this-in-production
NODE_ENV=development
PORT=3000
CORS_ORIGINS=http://localhost:5000,http://localhost:5173,http://127.0.0.1:5173,http://127.0.0.1:5000,*" > .env.wsl-temp

# Output WSL connection information for the client
echo -e "\n${GREEN}==== CONNECTION INFORMATION FOR CLIENT ====${NC}"
echo -e "Your WSL server will be available at: ${CYAN}http://${WSL_IP}:3000${NC}"
echo -e "Add this to your client's .env.local file as: ${CYAN}VITE_API_URL=http://${WSL_IP}:3000${NC}"
echo -e "${YELLOW}If you still have connection issues, add this to your hosts file:${NC}"
echo -e "${CYAN}${WSL_IP} wsl.local${NC}"
echo -e "${GREEN}============================================${NC}\n"

# Check for Node.js packages
echo -e "${YELLOW}Checking required packages...${NC}"
if ! command -v node &> /dev/null; then
  echo -e "${RED}Node.js is not installed. Please install Node.js and try again.${NC}"
  exit 1
fi

# Install required packages if needed
if [ ! -f "node_modules/.bin/nodemon" ]; then
  echo -e "${YELLOW}Installing required packages...${NC}"
  npm install dotenv express cors pg bcryptjs jsonwebtoken nodemon
fi

# Start the auth server with WSL-specific configuration
echo -e "\n${GREEN}Starting Auth Server on ${WSL_IP}:3000...${NC}"
echo -e "${YELLOW}This server will handle authentication requests from both WSL and Windows host.${NC}"

# Export needed environment variables
export NODE_ENV=development
export PORT=3000
export HOST=0.0.0.0

# Run with nodemon for auto-restart on changes
if command -v npx &> /dev/null; then
  npx nodemon simple-server-esm.js
else
  node simple-server-esm.js
fi